"""Notebook cell template for kaggle-tunnel (reversed-direction).

In this flow the **VM (notebook) runs the tunnel** — it starts an
embedded SSH server, a WebSocket proxy, and a cloudflared tunnel,
then registers in tunnelbroker.  The PC-side manager discovers the
instance and connects to it.

The cell:
  1. Installs required packages.
  2. Starts an embedded SSH server (asyncssh) on port 2222 capable of
     handling **multiple concurrent connections**.
  3. Starts an aiohttp WebSocket proxy that authenticates callers via
     the group bearer token and bridges WS ↔ local SSH server.
  4. Starts a **cloudflared tunnel** to expose the WS proxy publicly.
  5. Registers the tunnel URL + credentials in **tunnelbroker**.
  6. Keeps the tunnel alive; de-registers on shutdown / exception.

Authentication:
  - Only peers presenting the correct ``GROUP_TOKEN`` (via the
    ``x-kaggle-tunnel-token`` header or ``token`` query param) may
    open a WebSocket connection.  This ensures only group members
    can reach the embedded SSH server.

Render with::

    NOTEBOOK_CELL_TEMPLATE.format(
        instance_name=...,
        shared_secret=...,           # SSH password
        tunnelbroker_url=...,
        tunnelbroker_group=...,
        tunnelbroker_token=...,      # group bearer token (auth)
    )
"""

