async def main():
    import platform as _platform
    print(f"{{'='*60}}")
    print(f"  VM Tunnel Instance: {{INSTANCE_NAME}}")
    print(f"{{'='*60}}")
    print(f"  SSH: {{SSH_USER}}@{{SSH_HOST}}:{{SSH_PORT}}  password={{SHARED_SECRET}}")
    if TUNNELBROKER_TOKEN:
        print(f"  Group token auth: enabled")
    print()

    host_key = await start_ssh()
    print()

    cf_bin = _find_cloudflared()
    if not cf_bin:
        raise RuntimeError("cloudflared not found; cannot create tunnel")
    print(f"[kgl] Using cloudflared: {{cf_bin}}")
    print()

    proxy = WSProxy()
    app = aiohttp.web.Application()
    app.router.add_get("/ws", proxy.handle)
    app.router.add_get("/healthz", lambda r: aiohttp.web.Response(text="ok"))
    runner = aiohttp.web.AppRunner(app)
    await runner.setup()
    site = aiohttp.web.TCPSite(runner, "127.0.0.1", WS_PORT)
    await site.start()
    print(f"[kgl] WS proxy on {{SSH_HOST}}:{{WS_PORT}} (authenticated via group token)")

    cf_proc, pub_url = await start_cloudflared(cf_bin, WS_PORT)
    print()
    await tb_register(pub_url)
    print()

    print(f"[kgl] Instance running. Keep this cell alive.")
    print(f"[kgl] Endpoint: {{pub_url}}/ws")
    print(f"[kgl] Auth: x-kaggle-tunnel-token header or ?token= query param")
    print()
    try:
        while True:
            await asyncio.sleep(21600)
            await tb_register(pub_url)
            print(f"[kgl] Refreshed tunnelbroker registration")
    except asyncio.CancelledError:
        pass
    except Exception:
        traceback.print_exc()
    finally:
        print("[kgl] Shutting down...")
        await tb_deregister()
        if cf_proc and cf_proc.returncode is None:
            cf_proc.terminate()
            try:
                await asyncio.wait_for(cf_proc.wait(), timeout=5)
            except asyncio.TimeoutError:
                cf_proc.kill()
        await runner.cleanup()
        print("[kgl] Instance stopped")


